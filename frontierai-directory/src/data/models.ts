export const PROVIDERS = [...new Set(MODELS.map((m) => m.provider))];

export function formatContext(m: AIModel): string {
  if (m.contextLabel) return m.contextLabel;
  if (!m.context) return '—';
  if (m.context >= 1_000_000) return `${(m.context / 1_000_000).toFixed(0)}M`;
  return `${Math.round(m.context / 1000)}K`;
}

export function formatPrice(m: AIModel): string {
  if (m.pricing.input == null) return m.openWeight ? 'Self-hosted' : 'Subscription';
  return `$${m.pricing.input} / $${m.pricing.output}`;
}

export function formatReleased(iso: string): string {
  const [y, mo] = iso.split('-').map(Number);
  return new Date(y, mo - 1).toLocaleDateString('en-US', { month: 'short', year: 'numeric' });
}
